import AppKit
import Foundation

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date

    init(text: String, date: Date = Date()) {
        self.text = text
        self.date = date
    }

    static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        lhs.id == rhs.id
    }

    var preview: String {
        text.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

@MainActor
final class ClipboardStateViewModel: ObservableObject {
    static let shared = ClipboardStateViewModel()

    static let capacity = 10

    @Published private(set) var items: [ClipboardItem] = []

    var isEmpty: Bool { items.isEmpty }

    private var pasteboard: NSPasteboard { .general }
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Types password managers stamp on the pasteboard to opt out of clipboard
    /// history. Honouring them keeps secrets out of the buffer.
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        startMonitoring()
    }

    func startMonitoring() {
        guard timer == nil else { return }
        let timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.pollPasteboard()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    private func pollPasteboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if let types = pasteboard.types, !Self.excludedTypes.isDisjoint(with: Set(types)) { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        store(text)
    }

    /// Adds text to the ring buffer, newest first. Re-copying something that is
    /// already held moves it back to the front instead of duplicating it.
    func store(_ text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        var updated = items
        updated.removeAll { $0.text == text }
        updated.insert(ClipboardItem(text: text), at: 0)
        if updated.count > Self.capacity {
            updated.removeLast(updated.count - Self.capacity)
        }
        items = updated
    }

    func copyToPasteboard(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        // Claim the change we just made so the poll below doesn't re-capture it.
        lastChangeCount = pasteboard.changeCount
        store(item.text)
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        items.removeAll()
    }
}
